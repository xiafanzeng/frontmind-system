def apply_manual_reviews(index: dict[str, Any]) -> dict[str, Any]:
    """Return an index copy with only the protected observation fields overlaid."""
    output = deepcopy(index)
    patterns = {
        pattern.get("pattern_id"): pattern
        for pattern in output.get("patterns", [])
        if isinstance(pattern, dict)
    }
    for pattern_id in LOCKED_PATTERN_IDS:
        pattern = patterns.get(pattern_id)
        if not pattern:
            raise ValueError(f"missing protected pattern {pattern_id}")
        for benchmark in pattern.get("benchmarks", []):
            benchmark_id = benchmark.get("benchmark_id")
            review = MANUAL_REVIEWS.get(str(benchmark_id))
            if review is None:
                raise ValueError(f"missing manual review for {benchmark_id}")
            for field in REVIEW_FIELDS:
                benchmark[field] = deepcopy(review[field])
    expected = {
        f"{pattern_id}-B{number:02d}"
        for pattern_id, benchmark_count in LOCKED_PATTERN_BENCHMARK_COUNTS.items()
        for number in range(1, benchmark_count + 1)
    }
    if set(MANUAL_REVIEWS) != expected:
        missing = sorted(expected - set(MANUAL_REVIEWS))
        extra = sorted(set(MANUAL_REVIEWS) - expected)
        raise ValueError(f"manual review identity mismatch; missing={missing}, extra={extra}")
    return output
