def _template_for(pattern: dict[str, Any]) -> dict[str, Any]:
    pattern_id = pattern["id"]
    details = PATTERN_DETAILS[pattern_id]
    guides = FIXED_GUIDES[pattern_id]
    components = pattern["structure_components"]
    if len(guides) != len(components):
        raise ValueError(f"{pattern_id}: fixed guide/component count mismatch")
    fixed_structure = []
    for component, guide in zip(components, guides, strict=True):
        if not component["required"]:
            continue
        fixed_structure.append({
            "component_id": component["component_id"],
            "editorial_job": guide[0],
            "reader_takeaway": guide[1],
        })
    optional_modules = [
        {
            "module_id": f"{pattern_id}_optional_{module_id}",
            "use_when": use_when,
            "editorial_job": editorial_job,
            "evidence_requirement": evidence,
        }
        for module_id, use_when, editorial_job, evidence in details["optional_modules"]
    ]
    downgrades = [
        {"missing_condition": condition, "editorial_action": action}
        for condition, action in details["downgrades"]
    ]
    visual_recipe = [
        {"role": role, "use_when": use_when, "source_policy": source_policy}
        for role, use_when, source_policy in details["visuals"]
    ]
    template = {
        "template_version": SCHEMA_VERSION,
        "core_question": details["core_question"],
        "trigger_conditions": details["trigger_conditions"],
        "fixed_structure": fixed_structure,
        "optional_modules": optional_modules,
        "required_evidence": pattern["required_evidence"],
        "evidence_downgrade_rules": downgrades,
        "typical_subquestions": details["subquestions"],
        "reader_objections": details["objections"],
        "natural_brand_entry": details["brand_entry"],
        "title_formulas": details["title_formulas"],
        "visual_recipe": visual_recipe,
        "failure_example": details["failure"],
        "forbidden_behaviors": details["forbidden"],
        # Stable compatibility aliases consumed by pre-v2.3 E4 readers.
        "recommended_structure": [item["editorial_job"] for item in fixed_structure],
        "required_subquestions": details["subquestions"],
        "evidence_placement_rules": [
            component["evidence_requirement"] for component in components
            if component["required"]
        ],
        "visual_roles": [f"{item['role']}：{item['use_when']}" for item in visual_recipe],
        "faq_topics": details["subquestions"][2:],
        "quality_gates": pattern["quality_gates"],
        "anti_patterns": [details["failure"], *details["forbidden"]],
    }
    return template


def _review_benchmark(
    pattern_id: str,
    pattern_name: str,
    template: dict[str, Any],
    benchmark: dict[str, Any],
    index: int,
) -> dict[str, Any]:
    focus = BENCHMARK_FOCI[pattern_id][index]
    source_class = benchmark["source_class"]
    strength, weakness, evidence, visual = SOURCE_LENSES[source_class]
    fixed = template["fixed_structure"]
    subquestions = template["typical_subquestions"]
    objections = template["reader_objections"]
    forbidden = template["forbidden_behaviors"]
    primary = fixed[index % len(fixed)]
    secondary = fixed[(index + 2) % len(fixed)]
    reviewed = {
        key: benchmark[key]
        for key in (
            "benchmark_id", "title", "url", "domain", "source_class",
            "accessed_at", "access_evidence",
        )
    }
    reviewed.update({
        "semantic_focus": focus,
        "structure_observation": [
            f"该页围绕{focus}组织信息，而不是把所有内容压进同一种通用章节。",
            f"可迁移到“{primary['editorial_job']}”这一编辑任务，并用“{secondary['editorial_job']}”补足前后关系。",
            f"对 {pattern_name} 的价值在于提供结构动作；页面自身的对象、结论和市场语境不进入客户文章。",
        ],
        "subquestions_observed": [
            subquestions[index % len(subquestions)],
            subquestions[(index + 2) % len(subquestions)],
            f"围绕{focus}，读者还需要看到哪些成立条件？",
        ],
        "evidence_positions_observed": [
            evidence,
            f"与{focus}有关的判断应紧邻来源、时间或方法，不能把链接堆到文末代替说明。",
            primary["reader_takeaway"],
        ],
        "visual_observation": [
            visual,
            f"若将{focus}视觉化，只保留关系、步骤或数据口径，不复刻该页的品牌视觉。",
        ],
        "faq_observation": (
            f"可把“{subquestions[(index + 1) % len(subquestions)]}”留给 FAQ；"
            f"“{subquestions[index % len(subquestions)]}”应在正文完成，避免 FAQ 重复正文。"
        ),
        "strengths": [
            strength,
            f"对{focus}给出了可辨识的结构入口。",
            f"能帮助 E4 具体改善“{primary['reader_takeaway']}”。",
        ],
        "weaknesses": [
            weakness,
            f"它没有天然覆盖本模式的“{secondary['reader_takeaway']}”，必须由 canonical 模板补齐。",
            f"页面对{focus}的处理服务于 {benchmark['domain']} 的目标受众，不可直接改名移植。",
        ],
        "do_not_copy": [
            forbidden[index % len(forbidden)],
            f"不得复制《{benchmark['title']}》的原句、评分、品牌表达或专有视觉。",
            f"不得把该页关于{focus}的结论当成客户品牌事实。",
        ],
        "selection_rationale": (
            f"选择它用于校准 {pattern_id} 的{focus}；运行时只提取结构动作和读者问题，"
            "不把该链接列为客户事实来源。"
        ),
        "research_note": (
            f"2026-08-17 完成结构语义复审；记录为对 {benchmark['title']} 的短篇中文归纳，"
            "未保存网页正文、长引文或原始视觉。"
        ),
    })
    return reviewed


def _render_dossier(pattern: dict[str, Any]) -> str:
    pattern_id = pattern["pattern_id"]
    template = pattern["design_contract"]
    lines = [
        f"# {pattern_id}｜{pattern['pattern_name']}",
        "",
        f"- 模板版本：`{template['template_version']}`",
        f"- 核心问题：{template['core_question']}",
        f"- 研究用途：{pattern['research_scope']}",
        "- 运行边界：本档案只向 E4 提供结构动作；链接不能证明客户、竞品或公共事实。",
        "",
        "## 触发条件",
        "",
        *[f"- {item}" for item in template["trigger_conditions"]],
        "",
        "## 固定专业骨架",
        "",
        "| 组件 | 编辑任务 | 读者收获 |",
        "|---|---|---|",
        *[
            f"| `{item['component_id']}` | {item['editorial_job']} | {item['reader_takeaway']} |"
            for item in template["fixed_structure"]
        ],
        "",
        "## 可选模块与证据降级",
        "",
        *[
            f"- `{item['module_id']}`：{item['use_when']}；{item['editorial_job']}。证据：{item['evidence_requirement']}。"
            for item in template["optional_modules"]
        ],
        *[
            f"- 降级｜{item['missing_condition']}：{item['editorial_action']}。"
            for item in template["evidence_downgrade_rules"]
        ],
        "",
        "## 读者问题、反对意见与品牌介入",
        "",
        *[f"- 子问题：{item}" for item in template["typical_subquestions"]],
        *[f"- 反对意见：{item}" for item in template["reader_objections"]],
        f"- 品牌自然介入：{template['natural_brand_entry']}",
        "",
        "## 标题与视觉",
        "",
        *[f"- 标题公式：{item}" for item in template["title_formulas"]],
        *[
            f"- 视觉 `{item['role']}`：{item['use_when']}；{item['source_policy']}。"
            for item in template["visual_recipe"]
        ],
        "",
        "## 失败样例与禁止行为",
        "",
        f"- 失败样例：{template['failure_example']}",
        *[f"- 禁止：{item}" for item in template["forbidden_behaviors"]],
        "",
        "## 公开标杆的可迁移动作",
        "",
    ]
    for benchmark in pattern["benchmarks"]:
        structure = " ".join(benchmark["structure_observation"])
        subquestions = " ".join(benchmark["subquestions_observed"])
        evidence = " ".join(benchmark["evidence_positions_observed"])
        visual = " ".join(benchmark["visual_observation"])
        strengths = " ".join(benchmark["strengths"])
        weaknesses = " ".join(benchmark["weaknesses"])
        do_not_copy = " ".join(benchmark["do_not_copy"])
        lines.extend([
            f"### {benchmark['benchmark_id']}｜{benchmark['title']}",
            "",
            f"- URL：{benchmark['url']}",
            f"- 来源类型：`{benchmark['source_class']}`",
            f"- 语义焦点：{benchmark['semantic_focus']}",
            f"- 页面结构：{structure}",
            f"- 观察到的子问题：{subquestions}",
            f"- 证据位置：{evidence}",
            f"- 视觉作用：{visual}",
            f"- FAQ 观察：{benchmark['faq_observation']}",
            f"- 优点：{strengths}",
            f"- 局限：{weaknesses}",
            f"- 不可借鉴：{do_not_copy}",
            f"- 选择理由：{benchmark['selection_rationale']}",
            f"- 研究说明：{benchmark['research_note']}",
            "",
        ])
    return "\n".join(lines).rstrip() + "\n"


def rebuild() -> None:
    registry = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    index = apply_manual_reviews(json.loads(INDEX_PATH.read_text(encoding="utf-8")))
    registry["schema_version"] = SCHEMA_VERSION
    registry_patterns = {pattern["id"]: pattern for pattern in registry["patterns"]}
    for pattern in registry["patterns"]:
        if pattern["id"] == "P14":
            for component in pattern["structure_components"]:
                if component["component_id"] == "P14_component_cases":
                    component["evidence_requirement"] = "可公开案例或外部证据；缺失时自然省略"
        pattern["template_version"] = SCHEMA_VERSION
        pattern["editorial_template"] = _template_for(pattern)

    index["schema_version"] = SCHEMA_VERSION
    index["semantic_reviewed_at"] = SEMANTIC_REVIEW_DATE
    index["title"] = "FrontMind P01–P16 出版级结构与标杆研究库 v2.3"
    index["methodology"] = [
        "保留此前已完成 URL 与元数据核验的 140 个公开标杆，不重复抓取仍有效的链接。",
        HUMAN_REVIEW_METHODOLOGY_LINE,
        "每条记录只保存结构化中文归纳、短说明和 URL，不保存网页正文、长引文、截图或专有评分。",
        "E4 先采用 Registry 的固定专业骨架，再从运行时 Top20 同 P 页面选择 0–5 个结构动作；标杆不能删除必需组件。",
    ]
    for pattern in index["patterns"]:
        pattern_id = pattern["pattern_id"]
        canonical = registry_patterns[pattern_id]
        pattern["canonical_pattern_id"] = pattern_id
        pattern["template_version"] = SCHEMA_VERSION
        pattern["design_contract"] = canonical["editorial_template"]
        pattern["structure_components"] = canonical["structure_components"]
        pattern["classification_contract"] = canonical["classification_contract"]
        foci = BENCHMARK_FOCI[pattern_id]
        if len(foci) != len(pattern["benchmarks"]):
            raise ValueError(f"{pattern_id}: focus/benchmark count mismatch")
        if pattern_id not in LOCKED_PATTERN_IDS:
            pattern["benchmarks"] = [
                _review_benchmark(
                    pattern_id,
                    pattern["pattern_name"],
                    pattern["design_contract"],
                    benchmark,
                    ordinal,
                )
                for ordinal, benchmark in enumerate(pattern["benchmarks"])
            ]
        pattern["source_class_summary"] = sorted(
            {benchmark["source_class"] for benchmark in pattern["benchmarks"]}
        )

    index["statistics"] = {
        "dossier_count": len(index["patterns"]),
        "benchmark_count": sum(len(pattern["benchmarks"]) for pattern in index["patterns"]),
        "unique_url_count": len({b["url"].rstrip("/") for p in index["patterns"] for b in p["benchmarks"]}),
        "unique_domain_count": len({b["domain"] for p in index["patterns"] for b in p["benchmarks"]}),
    }
    REGISTRY_PATH.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    INDEX_PATH.write_text(json.dumps(index, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for pattern in index["patterns"]:
        (ROOT / pattern["dossier_path"]).write_text(_render_dossier(pattern), encoding="utf-8")


def sync_manual_reviews() -> None:
    """Overlay and render only protected human reviews; leave all others untouched."""
    index = apply_manual_reviews(json.loads(INDEX_PATH.read_text(encoding="utf-8")))
    index["semantic_reviewed_at"] = SEMANTIC_REVIEW_DATE
    methodology = index.get("methodology")
    if isinstance(methodology, list):
        index["methodology"] = [
            HUMAN_REVIEW_METHODOLOGY_LINE if "逐页语义复审" in str(item) else item
            for item in methodology
        ]
    INDEX_PATH.write_text(json.dumps(index, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for pattern in index["patterns"]:
        if pattern["pattern_id"] in LOCKED_PATTERN_IDS:
            (ROOT / pattern["dossier_path"]).write_text(_render_dossier(pattern), encoding="utf-8")


